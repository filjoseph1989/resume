const { pool } = require('../db');

// Tables from the old normalized schema, replaced by the single `resumes` table.
const LEGACY_TABLES = [
  'profiles', 'skills', 'skill_categories', 'experiences', 'projects',
  'education', 'certifications', '"references"', 'publications'
];

async function initDB() {
  const client = await pool.connect();
  try {
    console.log('Beginning database schema initialization...');
    await client.query('BEGIN');

    await client.query(`DROP TABLE IF EXISTS ${LEGACY_TABLES.join(', ')} CASCADE`);

    // One row per resume; the whole resume is stored as a JSON document.
    await client.query(`
      CREATE TABLE IF NOT EXISTS resumes (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug VARCHAR(50) NOT NULL UNIQUE,
        data JSONB NOT NULL,
        updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      );
    `);

    // Migrate tables created before `id` existed (slug was the primary key).
    const { rowCount: hasId } = await client.query(`
      SELECT 1 FROM information_schema.columns
      WHERE table_name = 'resumes' AND column_name = 'id'
    `);
    if (!hasId) {
      await client.query('ALTER TABLE resumes DROP CONSTRAINT resumes_pkey');
      await client.query('ALTER TABLE resumes ADD CONSTRAINT resumes_slug_key UNIQUE (slug)');
      await client.query('ALTER TABLE resumes ADD COLUMN id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
      console.log('  Added auto-increment id to resumes');
    }

    await client.query('COMMIT');
    console.log('Database tables created successfully!');
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('Error initializing database:', err);
    throw err;
  } finally {
    client.release();
  }
}

if (require.main === module) {
  initDB()
    .then(() => {
      console.log('Schema setup completed.');
      process.exit(0);
    })
    .catch((err) => {
      console.error(err);
      process.exit(1);
    });
}

module.exports = initDB;
